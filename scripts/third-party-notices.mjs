#!/usr/bin/env node
// Writes the license notices for every npm package esbuild bundled into a
// dist file. The minified bundle strips the packages' own copyright headers,
// so their MIT terms are met by shipping this file next to the bundle.
//
//   node scripts/third-party-notices.mjs <esbuild-metafile> <output-file>

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const [metafile, output] = process.argv.slice(2);

if (!metafile || !output) {
    console.error('usage: third-party-notices.mjs <esbuild-metafile> <output-file>');
    process.exit(1);
}

const { inputs } = JSON.parse(readFileSync(metafile, 'utf8'));

const packageDirs = new Set();
for (const input of Object.keys(inputs)) {
    const match = input.match(/^(.*node_modules\/(?:@[^/]+\/)?[^/]+)\//);
    if (match) packageDirs.add(match[1]);
}

const notices = [...packageDirs]
    .map((dir) => {
        const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
        const licenseFile = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.(md|txt))?$/i.test(f));

        if (!licenseFile) {
            throw new Error(`${pkg.name} has no LICENSE file; add its notice by hand before publishing.`);
        }

        return { name: pkg.name, version: pkg.version, license: pkg.license, text: readFileSync(join(dir, licenseFile), 'utf8').trim() };
    })
    .sort((a, b) => a.name.localeCompare(b.name));

const rule = '-'.repeat(78);
const body = notices.map((n) => `${rule}\n${n.name}@${n.version} (${n.license})\n${rule}\n\n${n.text}\n`).join('\n');

writeFileSync(
    output,
    `Third-party software bundled into ${output.split('/').pop().replace(/\.LICENSE\.txt$/, '')}\n` +
        `Generated by scripts/third-party-notices.mjs. Do not edit by hand.\n\n${body}`,
);

console.log(`Wrote ${notices.length} notices to ${output}`);
