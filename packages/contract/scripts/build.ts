/* Builds @sigta-hq/contract:
     dist/css/components.css  every component stylesheet, compiled by Tailwind into
                              plain, self-contained CSS in @layer components
     dist/css/core.css        layer order + base + components (no Tailwind needed)
     dist/css/sigta.css       core + the Sigta theme and its fonts (drop-in)
     dist/css/*.css           tailwind bridge, theme, theme template, fonts
     dist/*.js                schema, example renderers, manifests, icons
   dist/css is committed: the Composer package ships it to Livewire apps. */
import { readdirSync, readFileSync, writeFileSync, mkdirSync, rmSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';

const pkg = join(dirname(fileURLToPath(import.meta.url)), '..');
const css = join(pkg, 'css');
const dist = join(pkg, 'dist');
const out = join(dist, 'css');
const work = join(pkg, '.build');
mkdirSync(out, { recursive: true });
mkdirSync(work, { recursive: true });

const banner = (what: string) => `/* Sigta UI — ${what}. Generated by packages/contract/scripts/build.ts; edit packages/contract/css/ instead. */\n`;
const LAYERS = '@layer properties, theme, base, components, utilities;\n';

// 1. Components: one entry importing every component stylesheet into the components layer.
const components = readdirSync(join(css, 'components')).filter((f) => f.endsWith('.css')).sort();
writeFileSync(join(work, 'entry.css'), [
    '@import "tailwindcss/theme.css" layer(theme) theme(inline reference);',
    '@import "../css/tailwind.css" theme(reference);',
    '@import "../css/motion.css" layer(components);',
    '@import "../css/prose.css" layer(components);',
    ...components.map((file) => `@import "../css/components/${file}" layer(components);`),
    '',
].join('\n'));
const cli = join(pkg, '../../node_modules/@tailwindcss/cli/dist/index.mjs');
execFileSync(process.execPath, [cli, '-i', join(work, 'entry.css'), '-o', join(work, 'components.css'), '--optimize'], { stdio: ['ignore', 'ignore', 'inherit'], cwd: pkg });
const compiled = readFileSync(join(work, 'components.css'), 'utf8').replace(/^\/\*! tailwindcss[^\n]*\n/, '');
writeFileSync(join(out, 'components.css'), banner('component stylesheet') + compiled);

// 2. Plain files.
const read = (file: string) => readFileSync(join(css, file), 'utf8');
const fonts = read('fonts.css').replaceAll('url("../fonts/', 'url("../../fonts/');
const theme = read('theme.css').replace('@import "./fonts.css";\n', '');
writeFileSync(join(out, 'base.css'), banner('base layer') + read('base.css'));
writeFileSync(join(out, 'tailwind.css'), read('tailwind.css'));
writeFileSync(join(out, 'fonts.css'), fonts);
writeFileSync(join(out, 'theme.css'), read('theme.css'));
writeFileSync(join(out, 'theme.example.css'), read('theme.example.css'));
const core = LAYERS + read('base.css') + '\n' + compiled;
writeFileSync(join(out, 'core.css'), banner('core: base + components, no theme') + core);
writeFileSync(join(out, 'sigta.css'), banner('drop-in: core + the Sigta theme') + core + '\n' + fonts + '\n' + theme);

// 3. TypeScript: schema, renderers, manifests, icons.
rmSync(join(dist, 'manifests'), { recursive: true, force: true });
execFileSync(process.execPath, [join(pkg, '../../node_modules/typescript/bin/tsc'), '-p', join(pkg, 'tsconfig.json')], { stdio: 'inherit' });
console.log(`contract: ${components.length} component stylesheets → dist/css`);
