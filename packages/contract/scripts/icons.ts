/* Regenerates icons/lucide.json and icons/lucide.php — the pinned icon set both runtimes render —
   from the Lucide SVGs the Blade runtime serves (mallardduck/blade-lucide-icons
   in vendor/), so <sigta:icon> and <Icon> can never draw different versions.
   Run after bumping that Composer package: node packages/contract/scripts/icons.ts */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../../..');
const svgDir = join(root, 'vendor/mallardduck/blade-lucide-icons/resources/svg/icons');
const lock = JSON.parse(readFileSync(join(root, 'composer.lock'), 'utf8'));
const version = [...lock.packages, ...(lock['packages-dev'] ?? [])].find((p) => p.name === 'mallardduck/blade-lucide-icons')?.version;

const icons: Record<string, string> = {};
for (const file of readdirSync(svgDir).filter((f) => f.endsWith('.svg')).sort()) {
    const svg = readFileSync(join(svgDir, file), 'utf8');
    const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, '').replace(/<\/svg>\s*$/, '');
    icons[file.replace(/\.svg$/, '')] = inner.replace(/\n\s*/g, '').trim();
}
const source = `mallardduck/blade-lucide-icons@${version}`;
writeFileSync(join(root, 'packages/contract/icons/lucide.json'), JSON.stringify({ source, icons }) + '\n');
// The same set as a PHP array for the Blade runtime: opcache keeps it in memory.
const php = (text: string) => `'${text.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
writeFileSync(join(root, 'packages/contract/icons/lucide.php'), `<?php\n\n// Generated by packages/contract/scripts/icons.ts from ${source} — do not edit.\n\nreturn [\n${Object.entries(icons).map(([name, inner]) => `    ${php(name)} => ${php(inner)},`).join('\n')}\n];\n`);
console.log(`${Object.keys(icons).length} icons from blade-lucide-icons ${version}`);
